/**
 * Decide exactly what goes into the archive.
 * Throws with a readable report if anything would fail to build.
 *
 * @returns {{ textFiles: Map<string,string>, copyPaths: string[], meta: object }}
 */
export function planExport({ has, read, allPaths, options = {} }) {
  const manifestSrc = read('src/lib/modules.js');
  if (!manifestSrc) throw new Error('src/lib/modules.js לא נמצא — לא ניתן לייצא');
  const modulePages = parseModuleManifest(manifestSrc);
  const allModules = Object.keys(modulePages);

  // "All" means all modules present in THIS bundle, not everything the manifest
  // declares — a partial export still carries the full manifest.
  const availableModules = allModules.filter((id) =>
    (modulePages[id] || []).some((page) => has(`src/pages/${page}.jsx`))
  );
  const modules = options.modules?.length ? options.modules : availableModules;
  const sections = options.settingsSections?.length
    ? options.settingsSections
    : Object.keys(SETTINGS_PANEL_FILES);
  const devTools = options.devTools !== false;
  // Branding supplied by the export step. When present the bundle ships already
  // branded for that client — nothing to configure after deploying.
  const identity = options.identity ? buildIdentity(options.identity) : null;
  const blankTemplate = options.blankTemplate === true || (!!identity && !identity.name);
  const features = Object.keys(OPTIONAL_FEATURES).filter((id) =>
    options.features ? options.features.includes(id) : true
  );

  const unknown = modules.filter((m) => !allModules.includes(m));
  if (unknown.length) throw new Error(`מודולים לא מוכרים: ${unknown.join(', ')}`);

  const absent = modules.filter((m) => !availableModules.includes(m));
  if (absent.length) {
    throw new Error(
      `המודולים הבאים אינם קיימים בחבילה הזו ולכן לא ניתן לייצא אותם: ${absent.join(', ')}\n` +
      `זמינים כאן: ${availableModules.join(', ')}`
    );
  }
  if (modules.length === 0) throw new Error('לא נבחר אף מודול');

  const entries = new Set(['index.html', 'src/main.jsx', 'src/index.css']);
  for (const mod of modules) for (const p of modulePages[mod] || []) entries.add(`src/pages/${p}.jsx`);
  for (const p of CORE_PAGES) entries.add(`src/pages/${p}.jsx`);
  if (modules.includes('settings')) {
    for (const id of sections) {
      const f = SETTINGS_PANEL_FILES[id];
      if (f && has(f)) entries.add(f);
    }
    // The export UI is only reachable through a glob, so seed it explicitly —
    // and only when this bundle is meant to keep exporting.
    if (devTools) entries.add('src/components/settings/ExportDialog.jsx');
  }
  for (const id of features) {
    for (const f of OPTIONAL_FEATURES[id].files) if (has(f)) entries.add(f);
  }

  const { included, packages, missing } = walkGraph([...entries], has, read);

  if (missing.length) {
    const report = missing.slice(0, 40).map((m) => `  • ${m.file} → '${m.spec}'`).join('\n');
    throw new Error(`הייצוא נעצר: ${missing.length} ייבוא לא נפתר. החבילה לא הייתה נבנית.\n${report}`);
  }

  const textFiles = new Map();
  const copyPaths = [];

  const isBinary = (p) => /\.(png|jpe?g|gif|webp|ico|woff2?|ttf|otf|pdf|zip)$/i.test(p);
  const add = (p) => {
    if (!has(p)) return;
    if (isBinary(p)) copyPaths.push(p);
    else textFiles.set(p, read(p));
  };

  for (const name of ROOT_FILE_ALLOWLIST) add(name);
  for (const [name, content] of Object.entries(STATIC_FILES)) textFiles.set(name, content);
  for (const p of allPaths) {
    if (ROOT_DIR_ALLOWLIST.some((d) => p.startsWith(d))) add(p);
    if (devTools && DEV_TOOL_DIRS.some((d) => p.startsWith(d))) add(p);
  }

  for (const file of included) {
    if (!devTools && (/\.test\.(jsx?|tsx?)$/.test(file) || file.startsWith('src/test/'))) continue;
    add(file);
  }

  if (devTools) {
    // A test only ships when everything it imports is also in the bundle.
    // Otherwise a partial export carries a test for a module it does not have,
    // and `npm test` fails on a bundle that is otherwise perfectly fine.
    const included = new Set([...textFiles.keys(), ...copyPaths]);
    const resolvesInBundle = (file, content) =>
      extractSpecifiers(content).every((spec) => {
        // Node builtins resolve to nothing on disk but are always available.
        if (spec.startsWith('node:') || spec.includes('*') || packageNameOf(spec)) return true;
        const target = resolveSpecifier(spec, file, has);
        return target ? included.has(target) : false;
      });

    for (const p of allPaths) {
      if (p.startsWith('src/test/')) { add(p); continue; }
      if (!/^src\/.*\.test\.(jsx?|tsx?)$/.test(p)) continue;
      const content = read(p);
      if (content && resolvesInBundle(p, content)) add(p);
    }
  }

  // The only generated source files — all pure data, no code surgery.
  textFiles.set('src/lib/settingsSections.js', settingsSectionsFile(sections));
  textFiles.set('src/lib/features.js', featuresFile(features));

  if (identity || blankTemplate) {
    const applied = identity || BLANK_IDENTITY;
    const displayName = applied.name || 'App';
    const fullName = [applied.name, applied.subtitle].filter(Boolean).join(' — ') || 'App';

    textFiles.set('src/lib/appIdentity.js', appIdentityFile(applied));

    const manifest = JSON.parse(read('public/manifest.json') || '{}');
    // A data-URL logo is embedded straight into the manifest; the original brand
    // icons are dropped either way so no borrowed asset ever ships.
    const icons = applied.logo?.startsWith('data:')
      ? [{ src: applied.logo, sizes: '512x512', type: 'image/png', purpose: 'any maskable' }]
      : applied.logo && !applied.logo.startsWith('/icon-')
        ? [{ src: applied.logo, sizes: '512x512', type: 'image/png', purpose: 'any maskable' }]
        : [];
    textFiles.set('public/manifest.json', JSON.stringify({
      ...manifest,
      name: fullName,
      short_name: displayName,
      description: applied.subtitle || '',
      icons,
    }, null, 2) + '\n');
    // Drop the original brand assets rather than shipping someone else's logo.
    for (let i = copyPaths.length - 1; i >= 0; i--) {
      if (/^public\/icon-/.test(copyPaths[i])) copyPaths.splice(i, 1);
    }
    // Every human-visible string in the shell is emptied, so the template
    // carries no trace of the product it was exported from.
    textFiles.set('README.md', [
      `# ${displayName}`, '',
      applied.name
        ? `${[applied.name, applied.subtitle].filter(Boolean).join(' — ')}. Vite + React, עברית RTL.`
        : 'תבנית ריקה — Vite + React, עברית RTL, ללא מיתוג.', '',
      '```bash', 'npm install', 'cp .env.example .env.local', 'npm run dev', '```', '',
      'מיתוג: `הגדרות → אדמין → מיתוג`. מודולים ומסלולים: `src/lib/modules.js`.',
      'ייצוא ופריסה: `docs/DEPLOYMENT.md`.', '',
    ].join('\n'));

    const html = textFiles.get('index.html');
    if (html) {
      textFiles.set('index.html', html
        .replace(/<title>[\s\S]*?<\/title>/, `<title>${fullName}</title>`)
        .replace(/(<meta\s+(?:name|property)="(?:og:title|apple-mobile-web-app-title)"\s+content=")[^"]*"/g, `$1${fullName}"`)
        .replace(/(<meta\s+(?:name|property)="(?:description|og:description|og:site_name)"\s+content=")[^"]*"/g, `$1${applied.subtitle || ''}"`));
    }
  }

  const originalPkg = JSON.parse(read('package.json'));
  const { pkg, dropped } = prunePackageJson(originalPkg, packages, devTools);
  textFiles.set('package.json', JSON.stringify(pkg, null, 2) + '\n');

  const meta = {
    modules,
    availableModules,
    features,
    blankTemplate,
    identity: identity ? { name: identity.name, subtitle: identity.subtitle, hasLogo: !!identity.logo } : null,
    settingsSections: sections,
    devTools,
    files: included.size,
    droppedDependencies: dropped,
    exportedAt: new Date().toISOString(),
  };
  textFiles.set('selected_modules.json', JSON.stringify(meta, null, 2));

  return { textFiles, copyPaths, meta };
}
