const RESOLVE_EXTS = ['', '.jsx', '.js', '.ts', '.tsx', '.json', '.css'];
const INDEX_FILES = ['/index.jsx', '/index.js', '/index.ts', '/index.tsx'];

/** Parse src/lib/modules.js into { moduleId: [pageName, ...] }. */
export function parseModuleManifest(source) {
  const pages = {};
  const blocks = source.split(/^\s{2}(\w+):\s*\{$/m);
  for (let i = 1; i < blocks.length; i += 2) {
    const id = blocks[i];
    const found = [...(blocks[i + 1] || '').matchAll(/page:\s*'([^']+)'/g)].map((m) => m[1]);
    if (found.length) pages[id] = found;
  }
  return pages;
}

export function extractSpecifiers(code) {
  const out = [];
  const patterns = [
    /\bimport\s+[^'"();]*?\bfrom\s*['"]([^'"]+)['"]/g,
    /\bimport\s*['"]([^'"]+)['"]/g,
    /\bexport\s+[^'"();]*?\bfrom\s*['"]([^'"]+)['"]/g,
    /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
    /\brequire\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
    /@import\s+['"]([^'"]+)['"]/g,
  ];
  for (const re of patterns) {
    let m;
    while ((m = re.exec(code)) !== null) out.push(m[1]);
  }
  return out;
}

const dirname = (p) => p.slice(0, p.lastIndexOf('/') + 1) || './';

function normalize(p) {
  const parts = [];
  for (const seg of p.split('/')) {
    if (seg === '.' || seg === '') continue;
    if (seg === '..') parts.pop();
    else parts.push(seg);
  }
  return parts.join('/');
}

function tryPaths(base, has) {
  for (const ext of RESOLVE_EXTS) if (has(base + ext)) return base + ext;
  for (const idx of INDEX_FILES) if (has(base + idx)) return base + idx;
  return null;
}

export function resolveSpecifier(rawSpec, fromFile, has) {
  // Vite query suffixes (?raw, ?url, ?worker…) are not part of the path.
  const spec = rawSpec.split('?')[0];
  if (!spec) return null;
  if (spec.startsWith('@/')) return tryPaths(normalize('src/' + spec.slice(2)), has);
  if (spec.startsWith('/')) return tryPaths(normalize(spec.slice(1)), has);
  if (spec.startsWith('.')) return tryPaths(normalize(dirname(fromFile) + spec), has);
  return null;
}

export function packageNameOf(rawSpec) {
  const spec = rawSpec.split('?')[0];
  if (!spec) return null;
  if (spec.startsWith('.') || spec.startsWith('/') || spec.startsWith('@/')) return null;
  if (spec.startsWith('node:')) return null;
  const parts = spec.split('/');
  return spec.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

/**
 * Breadth-first walk of the import graph.
 * @param {(p:string)=>boolean} has   does this path exist?
 * @param {(p:string)=>string}  read  text contents of a path
 */
export function walkGraph(entries, has, read) {
  const included = new Set();
  const packages = new Set();
  const missing = [];
  const queue = [...entries];

  while (queue.length) {
    const file = queue.shift();
    if (included.has(file)) continue;
    if (!has(file)) { missing.push({ file: '(entry)', spec: file }); continue; }
    included.add(file);
    if (!/\.(jsx?|tsx?|css)$/.test(file)) continue;

    for (const spec of extractSpecifiers(read(file) || '')) {
      if (spec.includes('*')) continue; // import.meta.glob resolves against shipped files
      const pkg = packageNameOf(spec);
      if (pkg) { packages.add(pkg); continue; }
      const resolved = resolveSpecifier(spec, file, has);
      if (!resolved) { missing.push({ file, spec }); continue; }
      if (!included.has(resolved)) queue.push(resolved);
    }
  }
  return { included, packages, missing };
}

export function prunePackageJson(pkg, usedPackages, devTools) {
  const keep = (deps = {}) =>
    Object.fromEntries(
      Object.entries(deps).filter(([name]) =>
        !NEVER_EXPORT_DEPS.has(name) &&
        (usedPackages.has(name) || TOOLCHAIN_DEPS.has(name) || (devTools && DEV_TOOL_DEPS.has(name)))
      )
    );
  const out = {
    ...pkg,
    scripts: {
      dev: 'vite',
      build: 'vite build',
      preview: 'vite preview',
      lint: 'eslint . --quiet',
      ...(devTools ? {
        test: 'vitest run',
        'test:watch': 'vitest',
        export: 'node tools/export-cli.js',
        verify: 'node tools/export-matrix.js',
      } : {}),
    },
    dependencies: keep(pkg.dependencies),
    devDependencies: keep(pkg.devDependencies),
  };
  const dropped = [
    ...Object.keys(pkg.dependencies || {}),
    ...Object.keys(pkg.devDependencies || {}),
  ].filter((n) => !out.dependencies[n] && !out.devDependencies[n]);
  return { pkg: out, dropped };
}

